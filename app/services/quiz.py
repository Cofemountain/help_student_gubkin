def get_quiz_by_id(quiz_id: int) -> Optional[Dict]:
    for q in OGE_QUIZ_TASKS:
        if q["id"] == quiz_id:
            return q
    return None


def get_random_quiz(block: Optional[str] = None) -> Dict:
    if block:
        filtered = [q for q in OGE_QUIZ_TASKS if q["block"] == block]
        if filtered:
            return random.choice(filtered)
    return random.choice(OGE_QUIZ_TASKS)
