async def seed_bank_tasks() -> int:
    """Создает таблицу bank_tasks и наполняет открытый и закрытый банки задач с указанием авторства."""
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)

    async with AsyncSessionLocal() as session:
        inserted_count = 0
        updated_count = 0
        for item in BANK_TASKS_SEED:
            result = await session.execute(
                select(BankTask).where(
                    BankTask.title == item["title"],
                    BankTask.grade == item["grade"],
                    BankTask.bank_type == item["bank_type"],
                )
            )
            existing = result.scalar_one_or_none()
            if not existing:
                task = BankTask(
                    grade=item["grade"],
                    block=item["block"],
                    bank_type=item["bank_type"],
                    topic_title=item["topic_title"],
                    title=item["title"],
                    statement=item["statement"],
                    difficulty=item["difficulty"],
                    answer=item["answer"],
                    solution=item["solution"],
                    hint=item.get("hint"),
                    author=item.get("author"),
                )
                session.add(task)
                inserted_count += 1
            else:
                existing.author = item.get("author")
                existing.statement = item["statement"]
                existing.solution = item["solution"]
                existing.hint = item.get("hint")
                existing.difficulty = item["difficulty"]
                existing.answer = item["answer"]
                updated_count += 1

        await session.commit()
        total_open = await session.execute(select(BankTask).where(BankTask.bank_type == BankType.OPEN.value))
        total_closed = await session.execute(select(BankTask).where(BankTask.bank_type == BankType.CLOSED.value))
        open_cnt = len(total_open.scalars().all())
        closed_cnt = len(total_closed.scalars().all())

        print(f"✅ Банк задач физики успешно синхронизирован с авторством (Перышкин / Камзеева ФИПИ)!")
        print(f"• Новых задач: {inserted_count}, обновлено: {updated_count}")
        print(f"• Всего в Открытом банке: {open_cnt}")
        print(f"• Всего в Закрытом банке: {closed_cnt}")
        return inserted_count


if __name__ == "__main__":
    asyncio.run(seed_bank_tasks())
